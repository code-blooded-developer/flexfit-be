package com.harish.flexfit.enums;

public enum EquipmentType {
    // No equipment needed
    BODYWEIGHT,

    // Free weights (common in both home & gym)
    FREE_WEIGHT,        // dumbbells, barbells, kettlebells

    // Machines (mostly gym)
    MACHINE,            // leg press, chest press

    // Simple portable tools
    RESISTANCE,         // bands, tubes

    // Suspension / assisted bodyweight
    SUSPENSION,         // TRX

    // Cardio machines
    CARDIO_MACHINE,     // treadmill, cycle, elliptical

    // Outdoor / movement-based cardio
    CARDIO_ACTIVITY,    // running, skipping, cycling outdoor

    // Functional training gear
    FUNCTIONAL,         // battle ropes, sled, medicine ball

    // Mobility / flexibility
    MOBILITY,           // foam roller, yoga mat

    // Water-based training
    AQUATIC             // swimming pool
}
